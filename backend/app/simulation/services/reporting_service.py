"""Simulation Report Generator for Phase 10 Validation Laboratory.

Generates structured markdown audit reports for executed scenarios.
"""

from datetime import datetime, timezone
import json
from typing import Optional
from sqlalchemy.orm import Session

from app.models.simulation import SimulationRun, SimulationResult, SimulationReport
from app.simulation.scenario_registry import get_scenario


class ReportingService:
    """Creates and retrieves detailed markdown reports for simulation runs."""

    @staticmethod
    def generate_report_content(run: SimulationRun, result: SimulationResult) -> str:
        """Render a comprehensive markdown audit report."""
        scenario = get_scenario(run.scenario_id)
        scen_name = scenario.name if scenario else run.scenario_name
        category = scenario.category.value if scenario else "UNKNOWN"
        mitre_list = scenario.mitre_techniques if scenario else []
        mitre_str = "\n".join([f"- **{t}**" for t in mitre_list]) if mitre_list else "*None (Benign / Baseline)*"

        expected_rules = json.loads(result.expected_rules_json)
        actual_rules = json.loads(result.actual_rules_json)
        matched_rules = json.loads(result.matched_rules_json)
        unmatched_rules = json.loads(result.unmatched_rules_json)
        unexpected_rules = json.loads(result.unexpected_rules_json)
        failure_reasons = json.loads(result.failure_reasons_json)
        logs = json.loads(run.execution_log_json)

        status_emoji = "✅" if result.pass_status == "PASSED" else ("⚠️" if result.pass_status == "PARTIAL" else "❌")

        report = f"""# SentinelDLP Security Validation Report
**Scenario:** {scen_name} (`{run.scenario_id}`)
**Run ID:** `{run.id}`
**Execution Date:** {run.completed_at.strftime('%Y-%m-%d %H:%M:%S UTC') if run.completed_at else 'In Progress'}
**Outcome:** {status_emoji} **{result.pass_status}**
**Execution Duration:** {run.duration_ms} ms

---

## 1. Executive Summary
This report summarizes the defensive security validation run for scenario **{run.scenario_id}** ({category}).
SentinelDLP's detection pipeline was tested in an isolated sandbox to evaluate detection accuracy, rule fidelity, and operational stability.

- **Pass Status:** {result.pass_status}
- **Precision:** `{result.precision * 100:.1f}%`
- **Recall:** `{result.recall * 100:.1f}%`
- **F1 Score:** `{result.f1_score * 100:.1f}%`
- **False Positive Rate:** `{result.false_positive_rate * 100:.1f}%`
- **Detection Latency:** `{result.latency_ms:.1f} ms`

---

## 2. Threat & MITRE ATT&CK Mapping
The following adversarial techniques are exercised by this scenario:
{mitre_str}

---

## 3. Detection Rule Comparison
| Metric | Count | Details |
| :--- | :--- | :--- |
| **Expected Detection Rules** | {len(expected_rules)} | `{", ".join(expected_rules) if expected_rules else "None (Negative Control)"}` |
| **Observed Rules** | {len(actual_rules)} | `{", ".join(actual_rules) if actual_rules else "None"}` |
| **Matched Rules (True Positives)** | {len(matched_rules)} | `{", ".join(matched_rules) if matched_rules else "None"}` |
| **Missing Rules (False Negatives)** | {len(unmatched_rules)} | `{", ".join(unmatched_rules) if unmatched_rules else "None"}` |
| **Unexpected Rules (False Positives)** | {len(unexpected_rules)} | `{", ".join(unexpected_rules) if unexpected_rules else "None"}` |

---

## 4. Alert & Investigation Telemetry
- **Expected Security Alerts:** `{result.expected_alerts_count}` | **Observed:** `{result.actual_alerts_count}`
- **Expected Investigations:** `{result.expected_investigations_count}` | **Observed:** `{result.actual_investigations_count}`

"""
        if failure_reasons:
            report += "## 5. Diagnostic & Failure Analysis\n"
            for r in failure_reasons:
                report += f"- ❌ {r}\n"
            report += "\n---\n"

        report += "## 6. Execution Step Timeline\n"
        for entry in logs:
            step_num = entry.get("step_number", 0)
            action = entry.get("action", "")
            status = entry.get("status", "")
            msg = entry.get("message", "")
            ts = entry.get("timestamp", "")
            report += f"{step_num}. **[{action}]** `{status}`: {msg} *({ts})*\n"

        report += "\n---\n*Report automatically generated by SentinelDLP Detection Validation Laboratory (Phase 10).*\n"
        return report

    @staticmethod
    def get_report(db: Session, run_id: str) -> Optional[SimulationReport]:
        """Fetch saved simulation report by run ID."""
        return db.query(SimulationReport).filter(SimulationReport.run_id == run_id).first()
