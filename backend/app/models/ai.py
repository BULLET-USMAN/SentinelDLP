"""SQLAlchemy Models for Phase 9: AI-Powered SOC Analyst & Security Investigation.

Defines schemas for:
- AIInvestigationReport: Structured, validated AI investigation assessments.
- AIConversationSession: Bounded chat sessions scoped to investigations/alerts.
- AIConversationMessage: Sanitized conversation message history.
- AIToolAuditEvent: Immutable audit trail for every server-controlled tool call.
"""

import uuid
from datetime import datetime
from typing import Optional

from sqlalchemy import (
    Column,
    String,
    Text,
    Integer,
    Boolean,
    DateTime,
    ForeignKey,
    Index,
)
from sqlalchemy.orm import relationship

from app.db.base import Base


class AIInvestigationReport(Base):
    """Stores structured AI investigation reports generated by the SOC Analyst."""

    __tablename__ = "ai_investigation_reports"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    investigation_id = Column(
        String(36),
        ForeignKey("exfiltration_investigations.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    alert_id = Column(
        String(36),
        ForeignKey("security_alerts.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    model_id = Column(String(64), nullable=False, default="mock-sentinel-v1")
    provider_type = Column(String(32), nullable=False, default="mock")  # 'mock' or 'ollama'
    status = Column(String(32), nullable=False, default="COMPLETED")  # 'COMPLETED', 'FAILED', 'IN_PROGRESS'

    executive_summary = Column(Text, nullable=False)
    assessment = Column(Text, nullable=False)
    confidence_assessment = Column(
        String(32), nullable=False, default="PARTIAL_SUPPORT"
    )  # 'STRONG_SUPPORT', 'PARTIAL_SUPPORT', 'LIMITED_SUPPORT', 'INSUFFICIENT_EVIDENCE'
    evidence_completeness = Column(
        String(32), nullable=False, default="PARTIAL"
    )  # 'COMPLETE', 'PARTIAL', 'INSUFFICIENT'

    # Structured JSON data stored as Text for PostgreSQL compatibility
    observed_facts_json = Column(Text, nullable=False, default="[]")
    possible_explanations_json = Column(Text, nullable=False, default="[]")
    missing_evidence_json = Column(Text, nullable=False, default="[]")
    recommended_actions_json = Column(Text, nullable=False, default="[]")
    mitre_attack_mappings_json = Column(Text, nullable=False, default="[]")
    evidence_references_json = Column(Text, nullable=False, default="[]")

    tool_calls_count = Column(Integer, nullable=False, default=0)
    prompt_template_version = Column(String(16), nullable=False, default="v1.0")
    report_schema_version = Column(String(16), nullable=False, default="v1.0")

    # Analyst Review & Feedback
    analyst_review_status = Column(
        String(32), nullable=False, default="PENDING"
    )  # 'PENDING', 'USEFUL', 'INCORRECT', 'NEEDS_REVIEW'
    analyst_feedback_notes = Column(Text, nullable=True)
    reviewed_by = Column(String(64), nullable=True)
    reviewed_at = Column(DateTime, nullable=True)

    created_at = Column(DateTime, nullable=False, default=datetime.utcnow, index=True)
    execution_duration_ms = Column(Integer, nullable=False, default=0)

    # Relationships
    investigation = relationship("ExfiltrationInvestigation", backref="ai_reports")
    alert = relationship("SecurityAlert", backref="ai_reports")


class AIConversationSession(Base):
    """Bounded chat session scoped to an investigation or alert for SOC analyst inquiries."""

    __tablename__ = "ai_conversation_sessions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    investigation_id = Column(
        String(36),
        ForeignKey("exfiltration_investigations.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    alert_id = Column(
        String(36),
        ForeignKey("security_alerts.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    user_id = Column(String(64), nullable=False, default="soc_analyst")
    title = Column(String(255), nullable=False, default="Security Investigation Inquiry")
    status = Column(String(32), nullable=False, default="ACTIVE")  # 'ACTIVE', 'ARCHIVED'
    model_id = Column(String(64), nullable=False, default="mock-sentinel-v1")

    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    updated_at = Column(DateTime, nullable=False, default=datetime.utcnow, onupdate=datetime.utcnow, index=True)

    # Relationships
    messages = relationship(
        "AIConversationMessage",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="AIConversationMessage.created_at",
    )
    investigation = relationship("ExfiltrationInvestigation", backref="ai_sessions")
    alert = relationship("SecurityAlert", backref="ai_sessions")


class AIConversationMessage(Base):
    """Sanitized conversation message within an AI conversation session."""

    __tablename__ = "ai_conversation_messages"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    session_id = Column(
        String(36),
        ForeignKey("ai_conversation_sessions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    role = Column(String(16), nullable=False)  # 'user', 'assistant', 'system', 'tool'
    content = Column(Text, nullable=False)
    sanitized = Column(Boolean, nullable=False, default=True)

    evidence_references_json = Column(Text, nullable=True, default="[]")
    tool_invocations_json = Column(Text, nullable=True, default="[]")

    created_at = Column(DateTime, nullable=False, default=datetime.utcnow, index=True)

    session = relationship("AIConversationSession", back_populates="messages")


class AIToolAuditEvent(Base):
    """Immutable audit trail of server-controlled tools invoked during AI investigations."""

    __tablename__ = "ai_tool_audit_events"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    session_id = Column(String(36), nullable=True, index=True)
    report_id = Column(String(36), nullable=True, index=True)

    tool_name = Column(String(64), nullable=False, index=True)
    arguments_json = Column(Text, nullable=False, default="{}")
    resource_id = Column(String(64), nullable=True)
    status = Column(
        String(32), nullable=False, default="SUCCESS"
    )  # 'SUCCESS', 'DENIED', 'ERROR', 'BOUND_EXCEEDED'
    error_message = Column(Text, nullable=True)
    execution_duration_ms = Column(Integer, nullable=False, default=0)

    invoked_at = Column(DateTime, nullable=False, default=datetime.utcnow, index=True)
